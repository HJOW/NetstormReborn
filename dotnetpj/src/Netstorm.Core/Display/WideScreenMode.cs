namespace Netstorm.Core.Display;

/// <summary>
/// 화면비가 4:3 보다 넓을 때 게임 화면을 어떻게 배치할지 정한다.
/// 원본은 4:3 해상도(640×480·800×600·1024×768)만 지원했고, 와이드 모니터에서는 4:3 화면 좌우에 검은 여백이 생겼다
/// (플레이 영상 확인, LEFT_JOBS 1.7절). 16:9·16:10 은 원본에 없는 새 기능이며,
/// 2026-09-29 사용자 결정으로 와이드 화면은 <see cref="Extend"/> 로 동작한다.
/// </summary>
public enum WideScreenMode
{
    /// <summary>
    /// 시야 확장 (기본): 원본과 같은 픽셀 배율을 유지한 채 가로로 맵을 더 보여 준다.
    /// 원본에서 해상도를 높이면 더 넓은 맵이 보이던 동작과 같다.
    /// </summary>
    Extend,

    /// <summary>
    /// 레터박스 (개발용): 4:3 영역만 쓰고 남는 곳은 검게 둔다 (와이드 모니터의 원본 화면과 같다).
    /// 게임 동작으로는 쓰지 않는다 — 원본 캡처와 1024×768 로 겹쳐 볼 때만 사용한다.
    /// </summary>
    Letterbox,
}
