// VT → 항목의 조회 표다(선형 검색을 한 번만 Map 으로 만든다).
const BY_VTABLE = new Map(OBJECT_MENU_SLOTS.map((entry) => [entry.vtable, entry]));

// 현재 raw VT 값을 대응표에서 직접 찾는다. 등록되지 않은 VT 는 RangeError 다(C++ out_of_range). 입력은 부호 없는 32비트로 본다.
export function objectMenuSlots(vtable) {
    const entry = BY_VTABLE.get(vtable >>> 0);
    if (!entry) throw new RangeError('현재 객체메뉴 VT 미등록');
    return entry;
}
