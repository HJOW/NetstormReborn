const RECIPES_BY_ADDRESS = new Map(PATCH_CONSTRUCTOR_RECIPES.map((recipe) => [recipe.address, recipe]));
const RECIPE_VTABLES = new Set(PATCH_CONSTRUCTOR_RECIPES.map((recipe) => recipe.vtable));

// 타입 번호의 10.78 생성자 주소를 돌려준다. 표 밖 번호는 거부한다. (2026-11-06 WB04-D4)
export function typeConstructorAddress(number) {
    if (!Number.isInteger(number) || number < 0 || number >= PATCH_TYPE_CONSTRUCTORS.length) throw new RangeError('생성자 타입 번호 오류');
    return PATCH_TYPE_CONSTRUCTORS[number];
}

// 생성자 주소의 검증된 쓰기 목록을 돌려준다. 표에 없으면(null/assert/미복원 생성자) null 이다. (2026-11-06 WB04-D4)
export function constructorRecipe(address) {
    return RECIPES_BY_ADDRESS.get(address >>> 0) ?? null;
}

// recipe 의 쓰기를 같은 물리 슬롯에 순서대로 적용한다. OR 쓰기는 그 폭의 기존 바이트를 읽어 합친다. TYPE 조회·할당은 하지 않는다. (2026-11-06 WB04-D4)
export function applyConstructorRecipe(raw, recipe) {
    // 쓰기 순서와 폭을 그대로 지킨다.
    for (const [offset, width, orBits, value] of recipe.writes) {
        let current = value >>> 0;
        if (orBits) {
            // OR 에 필요한 그 폭의 기존 바이트만 읽는다.
            for (let index = 0; index < width; index += 1) current = (current | (raw[offset + index] << (index * 8))) >>> 0;
        }
        // 낮은 바이트부터 지정 폭만 쓴다(이웃 필드 보존).
        for (let index = 0; index < width; index += 1) raw[offset + index] = (current >>> (index * 8)) & 0xff;
    }
}

// 현재 VT 가 base 또는 검증된 자산 생성자의 최종 VT 인지 확인한다. TYPE 과 VT 의 쌍 일치는 강제하지 않는다(cpppj SupportsConstructedVtable). (2026-11-06 WB04-D4)
export function supportsConstructedVtable(table) {
    const value = table >>> 0;
    return value === SQUID_BASE_VTABLE || RECIPE_VTABLES.has(value);
}
