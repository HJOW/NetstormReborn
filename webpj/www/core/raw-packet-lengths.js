export function patchPacketLength(type) {
    if (!Number.isInteger(type) || type < 0 || type >= PATCH_PACKET_TYPE_COUNT) throw new RangeError('패킷 선언 길이 표의 타입 범위');
    return PATCH_PACKET_LENGTHS[type];
}
